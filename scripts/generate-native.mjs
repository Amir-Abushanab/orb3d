/**
 * `pnpm native:generate [--check]`: write what the native libraries embed from the built core:
 * the shader for every built-in kind of contents in Metal's and Android's dialects, and every
 * preset compiled to a program. A shader of your own travels in its program instead.
 *
 * The native code never re-implements the config model or the shader: it embeds these, so a
 * change in the core reaches iOS and Android by running this. `--check` writes nothing and fails
 * when a checked-in file is stale, which is how CI keeps them honest.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { parseArgs, run } from "./lib/cli.mjs";

const ROOT = resolve(import.meta.dirname, "..");
const DIST = resolve(ROOT, "packages/core/dist");
const SWIFT = resolve(ROOT, "native/apple/Sources/Orb3D/Generated.swift");
const KOTLIN = resolve(
  ROOT,
  "native/android/orb3d/src/main/java/io/github/amirabushanab/orb3d/Generated.kt",
);

const HEADER = "Generated by scripts/generate-native.mjs from @orb3d/core. Do not edit.";

await run(async () => {
  const args = parseArgs(process.argv.slice(2), { check: false });
  const { compileOrb, orbShader, VERTEX_SHADER } = await import(resolve(DIST, "program/index.js"));
  const { CONTENTS, CONTENTS_TYPES } = await import(resolve(DIST, "index.js"));
  const { PRESETS, PRESET_NAMES } = await import(resolve(DIST, "presets.js"));
  const programs = PRESET_NAMES.map((name) => [name, JSON.stringify(compileOrb(PRESETS[name]()))]);
  // One shader per kind of contents that has a built-in one: a picture and a clip share theirs.
  const shaders = [];
  for (const type of CONTENTS_TYPES) {
    const { shader } = CONTENTS[type];
    if (shader === "custom" || shaders.some(([name]) => name === shader)) continue;
    shaders.push([
      shader,
      orbShader("msl", { contents: type }),
      orbShader("glsl", { contents: type }),
    ]);
  }

  // Shader sources use raw multiline strings. Swift program JSON is quoted/escaped because
  // embedded GLSL starts with "#version; Kotlin JSON is chunked below the JVM constant limit.
  const swift = `// ${HEADER}
// swiftlint:disable all

/// The orb's shader for each built-in kind of contents, in Metal's dialect, both stages:
/// \`orbVertex\` and \`orbFragment\`. Keyed by a program's \`shader\`.
let orbMetalShaders: [String: String] = [
${shaders.map(([name, msl]) => `  "${name}": #"""\n${msl}"""#,`).join("\n")}
]

/// The built-in looks, compiled. Each has the states idle, listening, thinking, speaking and muted.
public enum OrbPreset: String, CaseIterable, Sendable {
${PRESET_NAMES.map((name) => `  case ${name}`).join("\n")}

  /// The preset as a program, ready for \`OrbView\` or \`OrbRuntime\`.
  public var program: OrbProgram {
    // swiftlint:disable:next force_try
    try! OrbProgram(json: json)
  }

  var json: String {
    switch self {
${programs.map(([name, json]) => `    case .${name}: ${JSON.stringify(json)}`).join("\n")}
    }
  }
}
`;

  const kotlin = `// ${HEADER}
@file:Suppress("ktlint", "MaxLineLength")

package io.github.amirabushanab.orb3d

/** The orb's vertex shader in GLSL ES 3.00, the dialect WebGL2 runs too. */
internal const val ORB_VERTEX_SHADER = """${VERTEX_SHADER}"""

/** The fragment shader for each built-in kind of contents, keyed by a program's \`shader\`. */
internal val ORB_FRAGMENT_SHADERS: Map<String, String> = mapOf(
${shaders.map(([name, , glsl]) => `  "${name}" to """${glsl}""",`).join("\n")}
)

/** The built-in looks, compiled. Each has the states idle, listening, thinking, speaking and muted. */
enum class OrbPreset(internal val json: String) {
${programs.map(([name, json]) => `  ${name.toUpperCase()}(listOf(${Array.from({ length: Math.ceil(json.length / 20000) }, (_, i) => `"""${json.slice(i * 20000, (i + 1) * 20000)}"""`).join(", ")}).joinToString(""))`).join(",\n")};

  /** The preset as a program, ready for \`OrbView\` or \`OrbRuntime\`. */
  val program: OrbProgram get() = OrbProgram.fromJson(json)
}
`;

  // Guard the delimiters: a state named with a quote and a hash, or a dollar sign (a template in
  // a Kotlin raw string), would otherwise end or rewrite a string silently.
  const embedded = [
    VERTEX_SHADER,
    ...shaders.flatMap(([, msl, glsl]) => [msl, glsl]),
    ...programs.map((p) => p[1]),
  ];
  const unsafe = ['"'.repeat(3), "$"];
  if (embedded.some((text) => unsafe.some((token) => text.includes(token)))) {
    throw new Error("generated content contains a raw-string delimiter or a $");
  }

  let stale = false;
  for (const [file, content] of [
    [SWIFT, swift],
    [KOTLIN, kotlin],
  ]) {
    let current = "";
    try {
      current = readFileSync(file, "utf8");
    } catch {
      // missing: stale
    }
    if (current === content) continue;
    if (args.check) {
      console.error(`stale: ${file.slice(ROOT.length + 1)} (run pnpm native:generate)`);
      stale = true;
    } else {
      writeFileSync(file, content);
      console.log(`wrote ${file.slice(ROOT.length + 1)}`);
    }
  }
  return !stale;
});
